import SportsKit
import SwiftUI

/// "This Week" on the lineup: on request, an AI briefing on the matchup, lineup gaps and injuries, from the
/// engine picked in Settings › Summaries, with the news stories behind it, each opening on espn.com.
struct WeekOverviewCard: View {
    let base: FantasyView.Base
    @Binding var overview: String?

    @State private var error: String?
    @State private var isLoading = false
    @AppStorage(RecapEngine.storageKey) private var engine = RecapEngine.onDevice

    /// News worth reading this week: starters with an injury or bye first, then the freshest, five at most.
    private var stories: [(player: FantasyPlayer, news: PlayerNews)] {
        let cutoff = Date.now.addingTimeInterval(-4 * 24 * 3600)
        let starters = base.team.starters
        return base.team.players.compactMap { player in base.news[player.id]?.first.map { (player, $0) } }
            .filter { $0.1.published > cutoff }
            .sorted { a, b in
                func rank(_ player: FantasyPlayer) -> Int {
                    (starters.contains(player.id) ? 0 : 2)
                        + ((player.injury != nil || player.team.flatMap { base.byes[$0] } == base.upcomingWeek) ? 0 : 1)
                }
                return (rank(a.0), b.1.published) < (rank(b.0), a.1.published)
            }
            .prefix(5).map { ($0.0, $0.1) }
    }

    var body: some View {
        SportsCard(title: "Week \(base.upcomingWeek) Briefing") {
            if let reason = engine.unavailableReason {
                Text(reason).font(.subheadline).foregroundStyle(.secondary).padding(.vertical, 4)
            } else if let overview {
                Text(overview).font(.body).lineSpacing(3).textSelection(.enabled).padding(.vertical, 6)
                HStack {
                    Label(engine == .claude ? "AI-generated by Claude from your league and ESPN news" : "AI-generated on this Mac from your league and ESPN news",
                          systemImage: "sparkles")
                        .font(.caption).foregroundStyle(.secondary)
                    Spacer()
                    Button("Refresh", systemImage: "arrow.clockwise", action: write)
                        .labelStyle(.iconOnly).buttonStyle(.glass).disabled(isLoading)
                }
            } else {
                HStack {
                    Text(error ?? "Your matchup, lineup gaps and injuries, and news that affects this week.")
                        .font(.subheadline).foregroundStyle(error == nil ? .secondary : Color.red)
                    Spacer()
                    if isLoading {
                        ProgressView().controlSize(.small)
                    } else {
                        Button("Brief Me", systemImage: "sparkles", action: write).buttonStyle(.glass)
                    }
                }
                .padding(.vertical, 4)
            }
            let stories = overview == nil ? [] : stories
            if !stories.isEmpty {
                Divider().padding(.vertical, 6)
                Text("Stories").font(.caption.weight(.semibold)).foregroundStyle(.secondary)
                ForEach(stories, id: \.news.id) { story in
                    StoryRow(player: story.player, news: story.news)
                }
            }
        }
    }

    private func write() {
        isLoading = true
        Task {
            do {
                overview = try await engine.weekOverview(team: base.team, week: base.upcomingWeek, matchup: base.matchup,
                                                         projections: base.projections, byes: base.byes, news: base.news)
                error = nil
            } catch {
                self.error = error.localizedDescription
            }
            isLoading = false
        }
    }
}

/// A news headline that opens the story in the browser.
struct StoryRow: View {
    let player: FantasyPlayer
    let news: PlayerNews

    var body: some View {
        let content = VStack(alignment: .leading, spacing: 2) {
            HStack {
                Text(player.name).font(.caption.weight(.semibold))
                Spacer()
                Text("\(news.source) · \(news.published.formatted(.relative(presentation: .named)))")
                    .font(.caption2).foregroundStyle(.tertiary)
                if news.url != nil {
                    Image(systemName: "arrow.up.right.square").font(.caption2).foregroundStyle(.secondary)
                }
            }
            Text(news.headline).font(.callout).multilineTextAlignment(.leading).lineLimit(2)
        }
        .padding(.vertical, 6)
        .contentShape(.rect)
        if let url = news.url {
            Link(destination: url) { content }.buttonStyle(.plain).help(url.absoluteString)
        } else {
            content
        }
    }
}
