import Foundation
import FoundationModels
import SportsKit

/// Who writes game summaries: Apple's on-device model (free, private, no setup) or Claude (needs an API key).
/// Both get the same prompt built from SportsKit's game data.
enum RecapEngine: String, CaseIterable, Identifiable {
    case onDevice, claude

    static let storageKey = "recapEngine"

    var id: Self { self }

    var title: String {
        switch self {
        case .onDevice: "On-Device"
        case .claude: "Claude"
        }
    }

    /// Shown under recaps.
    var credit: String {
        switch self {
        case .onDevice: "AI-generated on this Mac from ESPN game data"
        case .claude: "AI-generated by Claude from ESPN game data"
        }
    }

    /// Why this engine can't be used right now, or nil when it can.
    @MainActor var unavailableReason: String? {
        switch self {
        case .claude:
            return ClaudeKey.shared.value == nil ? "Add an Anthropic API key below to use Claude." : nil
        case .onDevice:
            switch SystemLanguageModel.default.availability {
            case .available: return nil
            case .unavailable(.appleIntelligenceNotEnabled): return "Turn on Apple Intelligence in System Settings to use the on-device model."
            case .unavailable(.deviceNotEligible): return "This Mac doesn’t support Apple Intelligence."
            case .unavailable(.modelNotReady): return "The on-device model is still downloading. Try again soon."
            case .unavailable: return "The on-device model isn’t available."
            }
        }
    }

    /// Key for the off-by-default setting that adds a described scoring play to score alerts.
    static let richAlertsKey = "richScoreAlerts"

    /// The engine picked in Settings.
    static var current: RecapEngine {
        UserDefaults.standard.string(forKey: storageKey).flatMap(RecapEngine.init) ?? .onDevice
    }

    @MainActor func recap(game: Game, detail: GameDetail) async throws -> String {
        try await complete(system: GamePrompt.system(for: game), user: GamePrompt.recap(game: game, detail: detail))
    }

    /// An answer to a fan's question, from this game's data only.
    @MainActor func answer(_ question: String, game: Game, detail: GameDetail) async throws -> String {
        try await complete(system: GamePrompt.askSystem, user: GamePrompt.ask(question, game: game, detail: detail))
    }

    /// A briefing on your fantasy week: matchup, lineup gaps and injuries, and news that matters.
    @MainActor func weekOverview(team: FantasyTeam, week: Int, matchup: FantasyMatchup?, projections: [String: Double],
                                 byes: [String: Int], news: [String: [PlayerNews]]) async throws -> String {
        try await complete(system: FantasyPrompt.weekSystem,
                           user: FantasyPrompt.week(team: team, week: week, matchup: matchup, projections: projections, byes: byes, news: news))
    }

    /// One line on a scoring play, for a notification.
    @MainActor func playLine(game: Game, play: Play) async throws -> String {
        try await complete(system: GamePrompt.playLineSystem, user: GamePrompt.playLine(game: game, play: play))
    }

    @MainActor private func complete(system: String, user: String) async throws -> String {
        switch self {
        case .claude:
            guard let service = ClaudeKey.shared.service else { throw ClaudeService.ClaudeError.http(401, "") }
            return try await service.complete(system: system, user: user)
        case .onDevice:
            let session = LanguageModelSession(instructions: system)
            return try await session.respond(to: user, options: GenerationOptions(temperature: 0.3)).content
                .trimmingCharacters(in: .whitespacesAndNewlines)
        }
    }
}
