<script lang="ts">
	// WeekOverviewCard.swift: on request, a Claude briefing on the matchup, lineup gaps and injuries, then the news
	// stories behind it, each opening on espn.com.
	import type { Team, Player, Matchup, News } from './fantasy';
	import { weekBriefing, getKey, ClaudeError } from './claude';
	let { team, week, matchup, projections, byes, news, briefing = $bindable() }: {
		team: Team; week: number; matchup?: Matchup; projections: Record<string, number>; byes: Record<string, number>; news: Record<string, News[]>; briefing?: string;
	} = $props();

	let error = $state<string | undefined>();
	let loading = $state(false);
	let canUseClaude = $state<boolean | undefined>();
	$effect(() => {
		getKey().then((k) => (canUseClaude = !!k));
	});

	/** News worth reading this week: starters with an injury or bye first, then the freshest, five at most. */
	const stories = $derived.by(() => {
		const starters = new Set(team.lineup.flatMap((s) => (s.player ? [s.player.id] : [])));
		const players = [...team.lineup.flatMap((s) => (s.player ? [s.player] : [])), ...team.bench];
		const rank = (p: Player) => (starters.has(p.id) ? 0 : 2) + (p.injury || (p.team && byes[p.team] === week) ? 0 : 1);
		return players
			.flatMap((p) => {
				const n = news[p.id]?.[0];
				return n && Date.now() - n.published.getTime() < 4 * 86_400_000 ? [{ p, n }] : [];
			})
			.sort((a, b) => rank(a.p) - rank(b.p) || b.n.published.getTime() - a.n.published.getTime())
			.slice(0, 5);
	});

	async function write() {
		loading = true;
		try {
			briefing = await weekBriefing(team, week, matchup, projections, byes, news);
			error = undefined;
		} catch (e) {
			error = e instanceof ClaudeError ? e.message : String(e);
		}
		loading = false;
	}

	/** In the desktop app a link would replace the app's own page, so stories open in the default browser instead. */
	async function open(e: MouseEvent, url: string) {
		if (!('__TAURI_INTERNALS__' in window)) return;
		e.preventDefault();
		(await import('@tauri-apps/plugin-opener')).openUrl(url);
	}
</script>

<section class="sports-card">
	<h2>Week {week} Briefing</h2>
	{#if canUseClaude === false}
		<p class="dim">Add an Anthropic API key in Settings › Summaries to have Claude brief you on your week.</p>
	{:else if briefing}
		<p class="text">{briefing}</p>
		<div class="row">
			<small>✦ AI-generated by Claude from your league and ESPN news</small>
			<button class="glass round" title="Refresh" aria-label="Refresh" disabled={loading} onclick={write}>↻</button>
		</div>
	{:else}
		<div class="row">
			<p class:error={!!error} class:dim={!error}>{error ?? 'Your matchup, lineup gaps and injuries, and news that affects this week.'}</p>
			{#if loading}<span class="spinner" aria-label="Writing"></span>{:else}<button class="glass action" onclick={write}>✦ Brief Me</button>{/if}
		</div>
	{/if}
	{#if briefing && stories.length}
		<hr />
		<span class="label">Stories</span>
		{#each stories as { p, n } (n.id + p.id)}
			<a class="story" href={n.url} target="_blank" rel="noopener noreferrer" onclick={(e) => n.url && open(e, n.url)}>
				<span class="meta"><b>{p.name}</b><span>{n.source}</span></span>
				<span class="headline">{n.headline}</span>
			</a>
		{/each}
	{/if}
</section>

