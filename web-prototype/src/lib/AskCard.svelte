<script lang="ts">
	// AskCard.swift: one-click questions are answered straight from the stats where they can be; typed questions,
	// and the few quick ones that need judgement, go to Claude when a key is set.
	import type { Game, GameDetail } from './espn';
	import { quickQuestions, answer, answerTyped, type QuickQuestion } from './facts';
	import { ask as askClaude, getKey, ClaudeError } from './claude';
	let { game, detail }: { game: Game; detail: GameDetail } = $props();

	const questions = $derived(quickQuestions(game.league.id));
	let question = $state('');
	let result = $state<{ asked: string; answer: string; fromStats: boolean } | undefined>();
	let error = $state<string | undefined>();
	let loading = $state(false);
	let canUseClaude = $state(false);
	$effect(() => {
		getKey().then((k) => (canUseClaude = !!k));
	});

	/** Stats first (quick questions, and typed ones naming a player or stat leader); Claude for the rest, when it can run. */
	async function ask(text: string, quick?: QuickQuestion) {
		text = text.trim();
		if (!text || loading) return;
		const stats = quick ? answer(quick, game, detail) : answerTyped(text, game, detail);
		if (stats) {
			[result, error] = [{ asked: text, answer: stats, fromStats: true }, undefined];
			if (!quick) question = '';
			return;
		}
		if (!canUseClaude) {
			[result, error] = [undefined, 'This one needs AI. Add a Claude key in Settings › Summaries.'];
			return;
		}
		loading = true;
		try {
			result = { asked: text, answer: await askClaude(text, game, detail), fromStats: false };
			error = undefined;
			if (!quick) question = '';
		} catch (e) {
			// Clear the previous answer, or it hides this error.
			[result, error] = [undefined, e instanceof ClaudeError ? e.message : String(e)];
		}
		loading = false;
	}
</script>

{#if game.status !== 'scheduled'}
	<section class="sports-card">
		<h2>Ask About the Game</h2>
		<!-- Free-form questions need Claude, so the box only shows when it can run. -->
		{#if canUseClaude}
			<form class="ask glass" onsubmit={(e) => (e.preventDefault(), ask(question))}>
				<input bind:value={question} placeholder={questions[0]?.text ?? 'Ask a question'} aria-label="Ask a question about the game" />
				{#if loading}
					<span class="spinner" aria-label="Thinking"></span>
				{:else}
					<button class="send" aria-label="Ask" disabled={!question.trim()}>↑</button>
				{/if}
			</form>
		{/if}
		<div class="chips">
			{#each questions as quick}
				<button class="chip glass" disabled={loading} onclick={() => ask(quick.text, quick)}>{quick.text}</button>
			{/each}
		</div>
		{#if result}
			<div class="answer">
				<strong>{result.asked}</strong>
				<p>{result.answer}</p>
				<small>{result.fromStats ? '📊 From ESPN game stats' : '✦ AI-generated by Claude from ESPN game data'}</small>
			</div>
		{:else if error}
			<p class="error" role="alert">{error}</p>
		{/if}
	</section>
{/if}

