<script lang="ts">
	// RecapCard.swift: ESPN's written story once a finished game has one, otherwise a summary built from the stats
	// (which follows a live game as it updates). Either can be rewritten by Claude when a key is set.
	import { type Game, type GameDetail } from './espn';
	import { summary } from './facts';
	import { recap, getKey, ClaudeError } from './claude';
	let { game, detail }: { game: Game; detail: GameDetail } = $props();

	let written = $state<string | undefined>();
	let error = $state<string | undefined>();
	let loading = $state(false);
	let fullStory = $state(false);
	let canUseClaude = $state(false);
	$effect(() => {
		getKey().then((k) => (canUseClaude = !!k));
	});
	const live = $derived(game.status === 'live');
	const story = $derived(live ? undefined : detail.overview.recap);

	async function summarise() {
		loading = true;
		try {
			written = await recap(game, detail);
			error = undefined;
		} catch (e) {
			error = e instanceof ClaudeError ? e.message : String(e);
		}
		loading = false;
	}
</script>

{#snippet footer(credit: string, icon: string)}
	<div class="footer">
		<span class="credit"><span aria-hidden="true">{icon}</span> {credit}</span>
		{#if story && !written && story.paragraphs.length > 2}
			<button class="link" onclick={() => (fullStory = !fullStory)}>{fullStory ? 'Show less' : 'Read more'}</button>
		{/if}
		<span class="grow"></span>
		{#if loading}
			<span class="spinner" aria-label="Writing"></span>
		{:else if canUseClaude}
			<button class="glass action" title={written ? 'Write it again with the latest plays' : 'Have Claude write it up instead'} onclick={summarise}>
				{written ? '↻ Rewrite' : '✦ Summarise with Claude'}
			</button>
		{/if}
	</div>
{/snippet}

{#if game.status !== 'scheduled'}
	<section class="sports-card recap">
		<h2>{live ? 'Catch Me Up' : 'Recap'}</h2>
		{#if written}
			<p>{written}</p>
			{@render footer('AI-generated by Claude from ESPN game data', '✦')}
		{:else if story}
			<strong class="headline">{story.headline}</strong>
			{#each fullStory ? story.paragraphs : story.paragraphs.slice(0, 2) as paragraph}<p>{paragraph}</p>{/each}
			{@render footer('Story from ESPN', '📰')}
		{:else}
			<!-- Rebuilt from the latest stats on every refresh of the game. -->
			<p>{summary(game, detail)}</p>
			{@render footer('From ESPN game stats', '📊')}
		{/if}
		{#if error}<p class="error" role="alert">{error}</p>{/if}
	</section>
{/if}

